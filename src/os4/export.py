def _sau_sheet(wb: Workbook) -> None:
    ws = wb.create_sheet("SAU")
    ws.cell(row=1, column=1, value="Single-attribute utility tables").font = TITLE
    col = 1
    for attribute in ATTRIBUTES + PROPOSED_ATTRIBUTES:
        table = sau_table(attribute)
        ws.cell(row=3, column=col, value=attribute).font = BOLD
        ws.cell(row=4, column=col, value=SOURCES[attribute]).font = NOTE
        _header(ws, 5, [f"x ({UNITS[attribute]})", "utility", "slope m to next point"], col)
        first, last = 6, 5 + len(table)
        for r, (x, u) in enumerate(zip(table["x"], table["utility"]), start=first):
            ws.cell(row=r, column=col, value=float(x))
            ws.cell(row=r, column=col + 1, value=float(u))
            if r < last:
                xc, uc = get_column_letter(col), get_column_letter(col + 1)
                slope = ws.cell(row=r, column=col + 2, value=f"=({uc}{r + 1}-{uc}{r})/({xc}{r + 1}-{xc}{r})")
                slope.fill = FORMULA_FILL
                slope.number_format = "0.000000"
        for offset, prefix in enumerate(("x", "u", "m")):
            letter = get_column_letter(col + offset)
            _name(wb, f"{prefix}_{attribute}", ws, f"${letter}${first}:${letter}${last}")
        _widths(ws, {col: 16, col + 1: 10, col + 2: 14, col + 3: 3})
        col += 4


def _weights_sheet(wb: Workbook) -> dict[str, dict[str, str]]:
    """Write every weight set; return the cell reference of each (set, attribute) weight."""
    ws = wb.create_sheet("Weights")
    ws.cell(row=1, column=1, value="MAU weights").font = TITLE
    _header(ws, 3, ["attribute", *WEIGHT_SETS])
    sets = {name: load_weights(name) for name in WEIGHT_SETS}
    attributes = ATTRIBUTES + PROPOSED_ATTRIBUTES
    refs: dict[str, dict[str, str]] = {name: {} for name in WEIGHT_SETS}
    for r, attribute in enumerate(attributes, start=4):
        ws.cell(row=r, column=1, value=attribute)
        for c, name in enumerate(WEIGHT_SETS, start=2):
            if attribute in sets[name]:
                ws.cell(row=r, column=c, value=sets[name][attribute])
                refs[name][attribute] = f"Weights!${get_column_letter(c)}${r}"
    total_row = 4 + len(attributes)
    ws.cell(row=total_row, column=1, value="sum (must be 1)").font = BOLD
    for c in range(2, 2 + len(WEIGHT_SETS)):
        letter = get_column_letter(c)
        cell = ws.cell(row=total_row, column=c, value=f"=SUM({letter}4:{letter}{total_row - 1})")
        cell.font = BOLD
        cell.fill = FORMULA_FILL
    notes = [
        "os3a_reweight: wait stays largest (OS3A MOE 4 is a direct match); weight moves from volume to",
        "availability because reliability (MOE 1) dominated the stakeholder evidence. See docs/PLAN.md Q8.",
        "os3a_extended: keeps the os3a_reweight priorities for the Appendix A four (x0.75) and gives 0.25",
        "to the proposed travel-time and bike-share attributes.",
    ]
    for i, text in enumerate(notes, start=total_row + 2):
        ws.cell(row=i, column=1, value=text).font = NOTE
    _widths(ws, {1: 20, 2: 14, 3: 14, 4: 14})
    return refs


def _cases_sheet(wb: Workbook, refs: dict[str, dict[str, str]]) -> None:
    ws = wb.create_sheet("Cases")
    ws.cell(row=1, column=1, value="Task 1: cases A-C").font = TITLE
    cases = evaluate_cases()
    compared = compare_weight_sets().set_index("case")
    four_attribute_sets = [name for name in WEIGHT_SETS if f"mau_{name}" in compared]

    raw = [f"{a} ({UNITS[a]})" for a in ATTRIBUTES]
    sau_cols = [f"u_{a}" for a in ATTRIBUTES]
    mau_cols = [h for name in four_attribute_sets for h in (f"mau_{name}", "rank", "python", "diff")]
    _header(ws, 3, ["case", *raw, *sau_cols, *mau_cols])
    first, last = 4, 3 + len(cases)
    n = len(ATTRIBUTES)
    for r, (_, row) in enumerate(cases.iterrows(), start=first):
        ws.cell(row=r, column=1, value=row["case"]).font = BOLD
        for i, a in enumerate(ATTRIBUTES):
            ws.cell(row=r, column=2 + i, value=float(row[a]))
            raw_cell = f"{get_column_letter(2 + i)}{r}"
            cell = ws.cell(row=r, column=2 + n + i, value=_sau_formula(raw_cell, a))
            cell.fill = FORMULA_FILL
            cell.number_format = "0.000"
        col = 2 + 2 * n
        for name in four_attribute_sets:
            terms = "+".join(
                f"{refs[name][a]}*{get_column_letter(2 + n + i)}{r}" for i, a in enumerate(ATTRIBUTES)
            )
            mau_cell = ws.cell(row=r, column=col, value=f"={terms}")
            mau_letter = get_column_letter(col)
            rank = ws.cell(row=r, column=col + 1,
                           value=f"=RANK({mau_letter}{r},${mau_letter}${first}:${mau_letter}${last})")
            python = ws.cell(row=r, column=col + 2, value=float(compared.loc[row["case"], f"mau_{name}"]))
            diff = ws.cell(row=r, column=col + 3,
                           value=f"=ABS({mau_letter}{r}-{get_column_letter(col + 2)}{r})")
            for cell in (mau_cell, rank, diff):
                cell.fill = FORMULA_FILL
            mau_cell.font = BOLD
            mau_cell.number_format = python.number_format = "0.0000"
            diff.number_format = "0.0E+00"
            col += 4
    ws.cell(row=last + 2, column=1,
            value="Hand check (Appendix A weights): A 0.613, B 0.639 (0.6385), C 0.651. "
                  "os3a_extended is not scored here: the cases give no travel time or bike share.").font = NOTE
    _widths(ws, {1: 7, **{c: 14 for c in range(2, 2 + 2 * n + 4 * len(four_attribute_sets))}})
    ws.row_dimensions[3].height = 32
    ws.freeze_panes = "B4"


def _sensitivity_sheet(wb: Workbook) -> None:
    ws = wb.create_sheet("Sensitivity")
    ws.cell(row=1, column=1, value="Weight sensitivity (Appendix A weights)").font = TITLE
    ws.cell(row=2, column=1,
            value="Each weight moved by delta; the other three rescaled so the weights still sum to 1. "
                  "Values from os4.utility.weight_sensitivity().").font = NOTE
    table = weight_sensitivity()
    _header(ws, 4, list(table.columns))
    for r, row in enumerate(table.itertuples(index=False), start=5):
        for c, value in enumerate(row, start=1):
            cell = ws.cell(row=r, column=c, value=value.item() if hasattr(value, "item") else value)
            if isinstance(value, float):
                cell.number_format = "0.000"
    _widths(ws, {1: 18, **{c: 11 for c in range(2, 2 + len(table.columns))}})


def add_task1_sheets(wb: Workbook) -> dict[str, dict[str, str]]:
    """Add the Task 1 sheets (README, SAU, Weights, Cases, Sensitivity) to ``wb``.

    Returns the weight cell references so the Task 2 sheets can reuse them.
    """
    _readme(wb)
    _sau_sheet(wb)
    refs = _weights_sheet(wb)
    _cases_sheet(wb, refs)
    _sensitivity_sheet(wb)
    return refs


def export_task1(path: Path = MODEL_PATH) -> Path:
    """Write the Task 1 backup workbook. ``export_model`` will add the Task 2 tabs to the same file."""
    path.parent.mkdir(parents=True, exist_ok=True)
    wb = Workbook()
    add_task1_sheets(wb)
    wb.save(path)
    return path


def export_model(scenario: Scenario, path: Path = MODEL_PATH) -> Path:
    """Write tabs: inputs, SAU/MAU tables and test cases, vehicle variants,
    the 5 architectures, and the hand-calc check. Returns the written path.
    """
    path.parent.mkdir(parents=True, exist_ok=True)
    wb = Workbook()
    refs = add_task1_sheets(wb)
    add_task2_sheets(wb, scenario, refs)
    wb.save(path)
    return path


